/* Browser-level smoke tests. Run from repository root after installing playwright + chromium. */
'use strict';
const {chromium}=require('playwright');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1280,height:900},acceptDownloads:true});
 const page=await context.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const url='file://'+path.resolve(__dirname,'index.html');
 await page.goto(url);
 await page.locator('#results input[type="checkbox"]').first().waitFor();
 assert.equal(await page.locator('#results input[type="checkbox"]').count(),484,'484 checkboxes on initial load');
 await page.locator('#results input[type="checkbox"]').first().check();
 assert.equal(await page.locator('#progress').innerText(),'1');
 await page.reload();
 assert.equal(await page.locator('#progress').innerText(),'1','checkbox persists across reload');
 page.once('dialog',d=>d.accept('QA second character'));
 await page.locator('#addChar').click();
 assert.equal(await page.locator('#progress').innerText(),'0','new character has separate progress');
 assert.equal(await page.locator('#character option').count(),2);
 const first=await page.locator('#character option').first().getAttribute('value');
 await page.locator('#character').selectOption(first);
 assert.equal(await page.locator('#progress').innerText(),'1','original character retains progress');
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#export').click();
 const download=await downloadPromise;
 const chunks=[];for await(const chunk of await download.createReadStream())chunks.push(chunk);
 const backup=JSON.parse(Buffer.concat(chunks).toString('utf8'));
 assert.equal(backup.app,'poe-all-ears');
 assert.equal(backup.characters.length,2);
 const bad={app:'poe-all-ears',version:1,characters:[{id:'fake',name:'bad',checked:[999]}]};
 await page.locator('#file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(bad))});
 assert.equal(await page.locator('#character option').count(),2,'invalid backup must not create characters');
 page.once('dialog',d=>d.accept());
 await page.locator('#file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
 assert.equal(await page.locator('#character option').count(),4,'valid import adds characters');
 await page.evaluate(()=>{window.__originalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(){throw Error('QuotaExceededError')};});
 const beforeCount=await page.locator('#character option').count();
 page.once('dialog',d=>d.accept('Must not persist'));
 await page.locator('#addChar').click();
 assert.equal(await page.locator('#character option').count(),beforeCount,'failed localStorage write must roll back character addition');
 const beforeProgress=await page.locator('#progress').innerText();
 await page.evaluate(()=>{document.querySelector('#results input[type="checkbox"]').click();});
 assert.equal(await page.locator('#progress').innerText(),beforeProgress,'failed localStorage write must roll back checkbox change');
 await page.evaluate(()=>{Storage.prototype.setItem=window.__originalSetItem;});
 await page.locator('#patch').selectOption('3.30');
 assert.equal(await page.locator('#results').isHidden(),true,'unsupported patch hides historical checklist');
 await page.locator('#patch').selectOption('legacy-3.9');
 assert.equal(await page.locator('#results').isVisible(),true);
 assert.deepEqual(errors,[],'browser JavaScript errors');
 await page.setViewportSize({width:375,height:812});
 await page.reload();
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2);
 assert.equal(overflow,false,'mobile horizontal overflow');
 const walk=await page.context().newPage();await walk.setViewportSize({width:375,height:812});
 const walkErrors=[];walk.on('pageerror',e=>walkErrors.push(e.message));
 await walk.goto('file://'+path.resolve(__dirname,'walkthrough.html'));
 assert.equal(await walk.locator('#guide').isVisible(),true,'walkthrough loads saved character');
 await walk.locator('#act').selectOption('9');
 assert.equal(await walk.locator('#counter').innerText(),'1 / 36','Act 9 has 36 Wiki-ordered steps');
 assert.equal(await walk.locator('#act2Branches').innerText().then(t=>t.includes('Highgate')),true,'Act 9 shows mutually exclusive ruler branch warning');
 await walk.locator('#act').selectOption('10');
 assert.equal(await walk.locator('#counter').innerText(),'1 / 32','Act 10 has 32 Wiki-ordered steps');
 await walk.locator('#act').selectOption('1');
 const walkBefore=await walk.locator('#actProgress').innerText();
 await walk.locator('#mark').click();
 const walkAfter=await walk.locator('#actProgress').innerText();
 assert.notEqual(walkAfter,walkBefore,'walkthrough mark updates progress');
 await page.reload();
 assert.equal(await page.locator('#results input[type="checkbox"]').first().isChecked(),await walk.locator('#mark').innerText().then(t=>t.includes('ยกเลิก')),'walkthrough and checklist share checkbox state');
 await walk.evaluate(()=>{window.__oldSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(){throw Error('QuotaExceededError')}});
 const oldActCount=await walk.locator('#actProgress').innerText();
 walk.once('dialog',d=>d.accept());
 await walk.locator('#mark').click();
 assert.equal(await walk.locator('#actProgress').innerText(),oldActCount,'walkthrough checkbox rollback on storage failure');
 await walk.evaluate(()=>{Storage.prototype.setItem=window.__oldSetItem});
 assert.deepEqual(walkErrors,[],'walkthrough browser JavaScript errors');
 const lore=await context.newPage();
 const loreErrors=[];lore.on('pageerror',e=>loreErrors.push(e.message));
 await lore.goto('file://'+path.resolve(__dirname,'companion.html'));
 await lore.locator('#loreList input[type="checkbox"]').first().waitFor();
 assert.equal(await lore.locator('#loreList input[type="checkbox"]').count(),140,'Lore companion lists 140 entries');
 await lore.locator('#loreList input[type="checkbox"]').first().check();
 assert.equal((await lore.locator('#loreTotal').innerText()).includes('1'),true,'Lore checkbox progress');
 await lore.reload();
 assert.equal(await lore.locator('#loreList input[type="checkbox"]').first().isChecked(),true,'Lore persists across reload');
 await lore.locator('#gameCount').fill('0');
 await lore.locator('#compare').click();
 assert.equal((await lore.locator('#compareResult').innerText()).includes('Checklist มากกว่าเกม 1'),true,'Recheck highlights count mismatch');
 await lore.locator('#gameCount').fill('1');
 await lore.locator('#compare').click();
 assert.equal((await lore.locator('#compareResult').innerText()).includes('ยอดตรงกัน'),true,'Recheck exact count');
 await lore.locator('#checkpoint').click();
 assert.equal((await lore.locator('#baselineText').innerText()).includes('1/140'),true,'Recheck baseline saved');
 await lore.locator('#showVaal').click();
 assert.equal(await lore.locator('#loreList input[type="checkbox"]').count(),16,'Vaal Letter and Journal group has 16');
 await lore.locator('#vaalArea').fill('Concealed Caldarium');
 await lore.locator('#lookup').click();
 assert.equal((await lore.locator('#vaalResult').innerText()).includes('#130'),true,'Vaal lookup resolves known area');
 await lore.locator('[data-safety="alira"]').check();
 assert.equal(await lore.locator('[data-safety="alira"]').isChecked(),true,'Act 2 safety box checked');
 await lore.reload();
 assert.equal(await lore.locator('[data-safety="alira"]').isChecked(),true,'Act 2 safety persists across reload');
 const firstLoreChar=await lore.locator('#character').inputValue();
 const firstLoreOption=await lore.locator('#character option').first().getAttribute('value');
 const secondLoreChar=firstLoreOption===firstLoreChar?await lore.locator('#character option').nth(1).getAttribute('value'):firstLoreOption;
 await lore.locator('#character').selectOption(secondLoreChar);
 assert.equal(await lore.locator('#loreList input[type="checkbox"]').first().isChecked(),false,'Lore independent by character');
 await lore.reload();
 assert.equal(await lore.locator('#character').inputValue(),secondLoreChar,'Lore selected character persists');
 await lore.locator('#character').selectOption(firstLoreChar);
 assert.equal(await lore.locator('#loreList input[type="checkbox"]').first().isChecked(),true,'Original Lore character intact');

 assert.deepEqual(loreErrors,[],'Companion JavaScript errors');
 await lore.setViewportSize({width:375,height:812});
 await lore.reload();
 assert.equal(await lore.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2),false,'Companion mobile horizontal overflow');
 const extras=await context.newPage();
 const extraErrors=[];extras.on('pageerror',e=>extraErrors.push(e.message));
 await extras.goto('file://'+path.resolve(__dirname,'extras.html'));
 await extras.locator('#items input[type="checkbox"]').first().waitFor();
 assert.equal(await extras.locator('#items input[type="checkbox"]').count(),91,'91 historical waypoint records');
 await extras.locator('#items input[type="checkbox"]').first().check();
 assert.equal(await extras.locator('#wayCount').innerText(),'1 / 91','Waypoint mark count');
 await extras.locator('#type').selectOption('sidequests');
 assert.equal(await extras.locator('#items input[type="checkbox"]').count(),30,'30 historical sidequests');
 await extras.locator('#items input[type="checkbox"]').first().check();
 await extras.reload();
 assert.equal(await extras.locator('#wayCount').innerText(),'1 / 91','Waypoint progress persists');
 assert.equal(await extras.locator('#questCount').innerText(),'1 / 30','Sidequest progress persists');
 const extrasFirst=await extras.locator('#character').inputValue();
 const firstExtraOption=await extras.locator('#character option').first().getAttribute('value');
 const extrasSecond=firstExtraOption===extrasFirst?await extras.locator('#character option').nth(1).getAttribute('value'):firstExtraOption;
 await extras.locator('#character').selectOption(extrasSecond);
 assert.equal(await extras.locator('#wayCount').innerText(),'0 / 91','Waypoints independent by character');
 await extras.reload();
 assert.equal(await extras.locator('#character').inputValue(),extrasSecond,'Extras selected character persists');
 await extras.locator('#character').selectOption(extrasFirst);
 assert.equal(await extras.locator('#wayCount').innerText(),'1 / 91','Original waypoint progress intact');

 await extras.setViewportSize({width:375,height:812});
 await extras.reload();
 assert.equal(await extras.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2),false,'Extras mobile horizontal overflow');
 assert.deepEqual(extraErrors,[],'Extra tracker browser JS errors');
 await browser.close();
 console.log('Browser smoke: PASS — 484 rows, persistence, multi-character, export/import, invalid JSON, patch gate, mobile width, walkthrough');
})().catch(e=>{console.error(e);process.exit(1)});
