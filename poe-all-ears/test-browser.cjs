async function verifyGuidedEntry(browser,url){
 const context=await browser.newContext({viewport:{width:320,height:812},hasTouch:true,reducedMotion:'reduce'});
 try{
   const page=await context.newPage();
   await page.goto(url+'#route');
   const task=page.locator('#hubView .hubWalkthrough');
   const taskTop=await task.evaluate(node=>Math.round(node.getBoundingClientRect().top));
   assert.equal(taskTop<406,true,'the first quest starts in the first half of a 320px viewport');
   console.log('Guided entry: 320px viewport, first quest at '+taskTop+'px');
   await page.keyboard.press('Tab');
   assert.equal(await page.locator('#hubSkip').evaluate(node=>node===document.activeElement),true,'keyboard entry starts with a skip link');
   await page.keyboard.press('Enter');
   assert.equal(await page.locator('#hubView').evaluate(node=>node===document.activeElement),true,'skip link moves focus to the active workspace');
   await page.locator('#hubCampaignAct').selectOption('2');
   await page.locator('.hubWalkNavigator select').selectOption('1');
   const confirmedPhase=await page.locator('.hubWalkthrough').getAttribute('data-phase');
   const confirmation=page.locator('.hubQuestConfirmation input');
   assert.equal(await page.locator('[data-stop-phase="old-fields"] button').getByText('กลับไปตรวจบทสนทนาที่ยังค้าง').count(),1,'Silk pre-quest dialogue is directly reachable from the unresolved STOP');
   await confirmation.check();
   const report=page.locator('.hubNextAction > .hubReport');
   const reportUrl=new URL(await report.getAttribute('href'));
   assert.equal(reportUrl.host,'github.com','feedback uses GitHub');
   assert.match(reportUrl.searchParams.get('body'),/Act: 2/,'report includes the current Act');
   assert.match(reportUrl.searchParams.get('body'),/ID: /,'report includes an ID field');
   assert.match(await report.innerText(),/GitHub/,'report discloses GitHub login');
   await page.reload();
   assert.equal(await page.locator('#hubCampaignAct').inputValue(),'2','reload restores the selected Act for this character');
   assert.equal(await page.locator('.hubWalkNavigator select').inputValue(),'1','reload restores the selected quest step for this character');
   assert.equal(await page.locator('.hubQuestConfirmation input').isChecked(),true,'manual quest confirmation survives reload');
   const layout=await task.evaluate(node=>{
     const selector=node.querySelector('.hubWalkNavigator select');
     const nav=selector.parentElement;
     const rect=selector.getBoundingClientRect();
     return {overflow:document.documentElement.scrollWidth>innerWidth,selectorUsesRow:rect.width>=nav.clientWidth-2};
   });
   assert.deepEqual(layout,{overflow:false,selectorUsesRow:true},'320px quest selector uses the full row without overflow');
   const firstCharacter=await page.locator('#character').inputValue();
   page.once('dialog',dialog=>dialog.accept('Independent route position'));
   await page.locator('#addChar').click();
   assert.equal(await page.locator('#hubCampaignAct').inputValue(),'1','a new character starts in Act 1');
   await page.locator('#character').selectOption(firstCharacter);
   assert.equal(await page.locator('.hubWalkNavigator select').inputValue(),'1','switching back restores that character’s last position');
   assert.equal(await page.locator('.hubQuestConfirmation input').isChecked(),true,'manual confirmation is restored for the original character');
   await page.locator('#hubNav [data-tab="review"]').click();
   const pendingDownload=page.waitForEvent('download');
   await page.getByRole('button',{name:'ดาวน์โหลด Backup รวม'}).click();
   const saved=await pendingDownload;
   const chunks=[];for await(const chunk of await saved.createReadStream())chunks.push(chunk);
   const backup=JSON.parse(Buffer.concat(chunks).toString('utf8'));
   assert.equal(backup.characters[0].confirmedStages['2:'+confirmedPhase],true,'combined export preserves manual quest confirmation');
   const reloaded=page.waitForEvent('load');
   page.once('dialog',dialog=>dialog.accept());
   await page.locator('#hubView input[type="file"]').setInputFiles({name:'roundtrip.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
   await reloaded;
   const imported=await page.locator('#character option').nth(2).getAttribute('value');
   await page.locator('#character').selectOption(imported);
   await page.locator('#hubNav [data-tab="route"]').click();
   await page.locator('#hubCampaignAct').selectOption('2');
   await page.locator('.hubWalkNavigator select').selectOption('1');
   assert.equal(await page.locator('.hubQuestConfirmation input').isChecked(),true,'import restores manually confirmed quest steps');
 }finally{await context.close();}
}

async function verifyEditorialGuidance(browser,url){
 const context=await browser.newContext({viewport:{width:820,height:1000}});
 try{
   const page=await context.newPage();
   await page.goto(url+'#route');
   const approved=await page.evaluate(()=>window.POE_APPROVED_GUIDANCE);
   const settings=page.locator('#hubSettings > summary');
   const chooseLanguage=async language=>{
     await settings.click();
     await page.locator('#hubDescriptionLanguage').selectOption(language);
     await settings.click();
   };
   await page.locator('.hubWalkNavigator select').selectOption('3');
   const mudflats=page.locator('[data-phase="mudflats"]');
   for(const language of ['th','en']){
     await chooseLanguage(language);
     assert.equal((await mudflats.locator('.hubWalkActions li').allTextContents()).includes(approved.undeadRhoas[language]),true);
     const warning=await mudflats.locator('[data-stop-phase]').innerText();
     assert.match(warning,/The Submerged Passage/);
     assert.match(warning,/The Fetid Pool/);
     assert.match(warning,/Glyph Wall/);
   }
   assert.equal(await mudflats.locator('input[data-track-type="ears"][data-track-id="21"]').count(),1,'approved Bestel wording retains the canonical checkbox');
   await page.locator('#hubCampaignAct').selectOption('8');
   await page.locator('.hubWalkNavigator select').selectOption('2');
   const cesspool=page.locator('[data-phase="doedre-cesspool"]');
   for(const language of ['th','en']){
     await chooseLanguage(language);
     assert.equal((await cesspool.locator('.hubWalkActions li').allTextContents()).includes(approved.toxicConduits[language]),true);
   }
   await cesspool.locator('.hubWalkArchive > summary').click();
   await cesspool.locator('[data-walk-extra="waypoints"] > summary').click();
   const waypoint=cesspool.locator('.hubItem').filter({has:page.locator('input[data-track-type="waypoints"][data-track-id="71"]')});
   assert.match(await waypoint.innerText(),/The Toxic Conduits/);
   assert.equal(await waypoint.locator('input').isChecked(),false,'visiting the guide never checks the waypoint');
   await waypoint.locator('.hubItemHelp > summary').click();
   assert.equal((await waypoint.locator('.hubFact span').allTextContents()).includes(approved.toxicConduits.en),true,'waypoint reference uses the same approved instruction');
 }finally{await context.close();}
}

